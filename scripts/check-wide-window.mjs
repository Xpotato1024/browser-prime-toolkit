import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {longMemoryContract} from '../native/long-window/memory-contract.mjs';
import {RUSQSIEVE_BASE64} from '../src/long-window/wasm-long-1024.js';
import {wideWorkerSource} from '../src/wide-window/worker-source.js';
import {selectResourcePlan as normalPlan} from '../src/graph-multicore/policy.js';
import {selectResourcePlan as longPlan} from '../src/long-window/policy.js';
import {selectResourcePlan} from '../src/wide-window/policy.js';
import {WIDE_LIMITS} from '../src/wide-window/budget.js';
const sha=b=>createHash('sha256').update(b).digest('hex'),read=p=>readFileSync(p);
const r=JSON.parse(read('native/long-window/build-long-1024.json')),old=JSON.parse(read('native/long-window/build-long-256.json'));
assert.equal(r.cleanBuilds,2);assert.equal(r.graphVariant,'long-1024');assert.equal(r.bytes,439917);
assert.equal(r.sha256,'9db5ac2f3d70ae61c6a277ddbfbe6386775f575f29e8c1312298d0be7e269037');
for(const k of ['commit','upstreamSha256','image','compiler','target','simd'])assert.deepEqual(r[k],old[k]);
for(const[p,h]of Object.entries(r.sourceHashes))assert.equal(sha(read(p)),h,p);
assert.deepEqual(r.args,old.args.map(x=>x==='-Clink-arg=--max-memory=268435456'?'-Clink-arg=--max-memory=1073741824':x));
assert.deepEqual(Object.keys(r.compiledSources),Object.keys(old.compiledSources));
for(const[p,h]of Object.entries(r.compiledSources))if(p!=='src/src/codex_observer.rs')assert.equal(h,old.compiledSources[p],p);
const b=Buffer.from(RUSQSIEVE_BASE64,'base64');assert.equal(sha(b),r.sha256);assert.deepEqual(longMemoryContract(b,1024),r.memory);assert.ok(r.memory.initialBytes<=2*1048576);
assert.throws(()=>normalPlan({mode:'manual',workers:5,memoryMiB:1536,timeBudgetMs:3600000}));
assert.throws(()=>longPlan({mode:'manual',workers:5,memoryMiB:1536,timeBudgetMs:3600000}));
const p=selectResourcePlan({mode:'manual',workers:5,memoryMiB:1536,timeBudgetMs:3600000});assert.equal(p.totalWasmBytes,1280*1048576);assert.deepEqual(p.ownerCapsMiB,[1024,64,64,64,64]);
for(const cap of [64,1024])assert.doesNotThrow(()=>new Function(wideWorkerSource(cap)));assert.throws(()=>wideWorkerSource(256));
assert.deepEqual(WIDE_LIMITS,{maxMs:3600000,maxFamilies:4096,maxEvents:16416,maxGraphSnapshots:512,maxProgress:4096});
const plan=JSON.parse(read('bench/staged-wide-window-plan.json'));assert.equal(plan.id,'llm01-wide-window-stage38');assert.equal(plan.trials.length,2);assert.equal(plan.trials.filter(t=>t.case==='RSA-100').length,1);
assert.equal(plan.trials.reduce((n,t)=>n+t.budgetMs+120000,0),plan.limits.totalCampaignMs);assert.equal(plan.adoption.commonPrefixFamilies,572);
for(const script of ['scripts/generate-wide-window.mjs','scripts/generate-wide-window-harness.mjs'])execFileSync(process.execPath,[script,'--check'],{stdio:'inherit'});
console.log('Wide explicit role/source/two-clean bounds, one-hour finite plan and ordinary-entry separation verified');
