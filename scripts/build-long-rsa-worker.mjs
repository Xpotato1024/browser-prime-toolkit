import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {writeGenerated} from './generated-file.mjs';
const paths=['src/core/integer-input.js','src/engine/options.js','src/engine/arithmetic.js','src/long-rsa/core-result.js',
 'src/long-rsa/options.js','src/long-rsa/factor.js','src/long-rsa/profile.js','src/long-rsa/install.js'];
const chunks=paths.map(path=>{
 let code=readFileSync(new URL('../'+path,import.meta.url),'utf8');
 code=code.replace(/^import .+ from '[^']+';\n/gm,'').replace(/^export (?=(?:async )?(const|class|function) )/gm,'');
 if(/^(import|export) /m.test(code)||/\bimport\s*\(/.test(code))throw Error('RSA unsupported module syntax '+path);
 if(path==='src/core/integer-input.js')code=code.replace(/\bfail\b/g,'rsaInputFail');
 return '// '+path+'\n'+code;
});
const code="'use strict';\n"+chunks.join('\n')+'\ninstallRsaWorker();\n';const checked=spawnSync(process.execPath,['--check','--input-type=module'],{input:code,encoding:'utf8'});
if(checked.status!==0)throw Error(checked.stderr);
writeGenerated(new URL('../src/long-rsa/worker-source.js',import.meta.url),'// Generated by scripts/build-long-rsa-worker.mjs; no runtime imports or WASM.\nexport const RSA_WORKER_SOURCE = '+JSON.stringify(code)+';\n');
console.log('Verified isolated RSA native Worker',Buffer.byteLength(code),'bytes');
