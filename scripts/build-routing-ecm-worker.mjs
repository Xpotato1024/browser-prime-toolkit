import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createGmpSplit} from '../src/engine/gmp.js';
import {GMP_BASE64} from '../src/engine/gmp-bytes.js';
import {ecmWorkerMain} from '../src/routing/ecm-worker-runtime.js';
const output=new URL('../src/routing/ecm-source.js',import.meta.url);
export function routingEcmModule(){
 const source="'use strict';\nconst GMP_BASE64="+JSON.stringify(GMP_BASE64)+
  ";\nconst createGmpSplit="+createGmpSplit.toString()+
  ";\n("+ecmWorkerMain.toString()+")(createGmpSplit,GMP_BASE64);\n";
 return '// SPDX-License-Identifier: AGPL-3.0-only\n'+
  '// Generated by scripts/build-routing-ecm-worker.mjs; do not hand edit.\n'+
  '// Existing GMP/ECM kernel terms and source are retained in SOURCE_OFFER.md.\n'+
  'export const ECM_WORKER_SOURCE = '+JSON.stringify(source)+';\n';
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const args=process.argv.slice(2);
 if(args.length>1||args.length===1&&args[0]!=='--check')throw Error('Expected optional --check');
 const expected=routingEcmModule();
 if(args[0]==='--check'){
  if(await readFile(output,'utf8')!==expected)throw Error('Routing ECM Worker source is stale');
  console.log('Routing ECM Worker source and reviewed inputs are current');
 }else{
  await writeFile(output,expected,'utf8');
  console.log('Generated routing ECM Worker before host bundling');
 }
}
