import {readFileSync,writeFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
import {compileInContainer} from './container-compile.mjs';
import {patchSiqs} from './patch-siqs.mjs';
const root=resolve(import.meta.dirname,'..');
const image='emscripten/emsdk@sha256:27bc6267cb285223b8aebb7627bfebae7cb3ad2aaa0d5923b8aa5321793033e8';
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const names=JSON.parse(readFileSync(join(root,'native/siqs/sources.json')));
const files={}, patched={};
for (const item of names) {
  const bytes=readFileSync(join(root,item.source));
  if(sha(bytes)!==item.sha256) throw Error('SIQS source pin '+item.source);
  const result=patchSiqs(item.destination,bytes.toString());
  files['src/'+item.destination]=Buffer.from(result.text);
  patched[item.destination]={sha256:result.sha256,changes:result.changes};
}
const own=['native/siqs/runtime.c','native/siqs/runtime.h','native/siqs/matrix.c','native/siqs/sanitize.c'];
for(const path of own) files['src/'+path]=readFileSync(join(root,path));
const script=`set -eu
cd /src
FLAGS="-O2 -std=gnu99 -DCPU_GENERIC -D_GMP_XFACE_H_ -Iinclude -Impqs -Inative/siqs -fwasm-exceptions -sSUPPORT_LONGJMP=wasm"
for n in mpqs poly relation sieve sqrt; do emcc $FLAGS -include native/siqs/runtime.h -c mpqs/$n.c -o /work/$n.o; done
`;
const commandScript=script+`
for n in mp prime_delta prime_sieve squfof; do emcc $FLAGS -include native/siqs/runtime.h -c common/$n.c -o /work/$n.o; done
for b in 32 64; do emcc $FLAGS -include native/siqs/runtime.h -DCPU_GENERIC -DBLOCK_KB=$b -DROUTINE_NAME=qs_core_sieve_generic_"$b"k -c mpqs/sieve_core.c -o /work/core$b.o; done
emcc $FLAGS -c native/siqs/runtime.c -o /work/runtime.o
emcc $FLAGS -c native/siqs/matrix.c -o /work/matrix.o
emcc /work/*.o -O2 -fwasm-exceptions -sSUPPORT_LONGJMP=wasm --no-entry -sSTANDALONE_WASM=1 -sFILESYSTEM=0 -sALLOW_MEMORY_GROWTH=0 -sINITIAL_MEMORY=67108864 -sSTACK_SIZE=1048576 -sMALLOC=emmalloc '-sEXPORTED_FUNCTIONS=["_input_ptr","_factor_ptr","_siqs_split","_stat_live","_stat_peak","_stat_phases","_stat_reason","_configure_fault","_stat_line","_log_ptr","_stat_allocs"]' -o /work/siqs.wasm
`;
if(process.argv.includes('--native')) {
  let native=commandScript.slice(0,commandScript.indexOf('emcc /work/*.o'));
  native=native.replaceAll('emcc','cc').replace('-O2 -std=gnu99','-O1 -g -fsanitize=address,undefined -fno-omit-frame-pointer -DPRIME_NATIVE_TESTS -std=gnu99').replace(' -fwasm-exceptions -sSUPPORT_LONGJMP=wasm','');
  native+='cc -O1 -g -fsanitize=address,undefined -DPRIME_NATIVE_TESTS -Inative/siqs -c native/siqs/sanitize.c -o /work/sanitize.o\ncc -fsanitize=address,undefined /work/*.o -lm -o /work/sanitize\nASAN_OPTIONS=detect_leaks=1:abort_on_error=1 UBSAN_OPTIONS=halt_on_error=1 /work/sanitize\n';
  if(process.argv.includes('--quick')) native=native.replaceAll('-DPRIME_NATIVE_TESTS','-DPRIME_NATIVE_TESTS -DPRIME_NATIVE_QUICK');
  files['src/native-build.sh']=Buffer.from(native);
  const output=compileInContainer(image,files,['sh','/src/native-build.sh'],'true',600000,'candidate');
  console.log(output.toString());process.exit(0);
}
files['src/build.sh']=Buffer.from(commandScript);
const hashes=Object.fromEntries([...own,'native/siqs/sources.json','scripts/patch-siqs.mjs','scripts/build-siqs.mjs','scripts/container-compile.mjs'].map(p=>[p,sha(readFileSync(join(root,p)))]));
const builds=[];
for(let i=0;i<2;i++) {
  builds.push(compileInContainer(image,files,['sh','/src/build.sh'],'cat /work/siqs.wasm',180000));
}
if(!builds[0].equals(builds[1])) throw Error('SIQS clean builds differ');
const bytes=builds[0],module=new WebAssembly.Module(bytes);
const receipt={image,sourceHashes:hashes,upstreams:names,patched,script:commandScript,cleanBuilds:2,bytes:bytes.length,sha256:sha(bytes),imports:WebAssembly.Module.imports(module),exports:WebAssembly.Module.exports(module),memoryLimitBytes:67108864,stackBytes:1048576,managedHeapBytes:33554432};
const output='// Generated by build-siqs.mjs; private bounded SIQS evaluation.\nexport const SIQS_BASE64 = '+JSON.stringify(bytes.toString('base64'))+';\n';
if(process.argv.includes('--check')) {
  if(readFileSync(join(root,'src/engine/siqs-bytes.js'),'utf8')!==output || JSON.stringify(JSON.parse(readFileSync(join(root,'native/siqs/build.json'))))!==JSON.stringify(receipt)) throw Error('SIQS artifact stale');
} else {
  writeFileSync(join(root,'src/engine/siqs-bytes.js'),output); writeFileSync(join(root,'native/siqs/build.json'),JSON.stringify(receipt,null,2)+'\n');
}
console.log('Two clean bounded SIQS WASM builds matched',bytes.length,sha(bytes),receipt.imports);
