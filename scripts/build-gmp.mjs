import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { createHash } from 'node:crypto';
import { compileInContainer } from './container-compile.mjs';

const root = resolve(import.meta.dirname, '..'), directory = process.env.PRIME_UPSTREAM_DIR;
if (!directory) throw Error('Set PRIME_UPSTREAM_DIR to the verified source cache');
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const image = 'emscripten/emsdk@sha256:27bc6267cb285223b8aebb7627bfebae7cb3ad2aaa0d5923b8aa5321793033e8';
const upstreams = JSON.parse(readFileSync(join(root, 'native/gmp/upstreams.json')));
const provenance = JSON.parse(readFileSync(join(root, 'vendor/msieve-siqs/provenance.json')));
const files = {};
for (const entry of upstreams) {
  const bytes = readFileSync(join(directory, entry.file));
  if (bytes.length !== entry.bytes || sha(bytes) !== entry.sha256) throw Error('Upstream hash mismatch: ' + entry.file);
  files['build/' + entry.file] = bytes;
}
const inputs = ['native/gmp/bridge.c', 'native/gmp/build.sh', 'native/gmp/sanitize.c',
  'native/gmp/upstreams.json', 'scripts/build-gmp.mjs', 'scripts/container-compile.mjs',
  'vendor/msieve-siqs/provenance.json', ...provenance.files.map(f => 'vendor/msieve-siqs/' + f.path)];
for (const file of provenance.files) {
  const bytes = readFileSync(join(root, 'vendor/msieve-siqs', file.path));
  if (bytes.length !== file.bytes || sha(bytes) !== file.sha256) throw Error('SIQS source hash mismatch');
}
for (const path of inputs.filter(p => !p.startsWith('scripts/'))) files['src/' + path] = readFileSync(join(root, path));
if (process.argv.includes('--native')) {
  const output = compileInContainer(image, files, ['sh', '/src/native/gmp/build.sh', 'native'], 'true', 600000, 'candidate');
  if (!output.toString().includes('native sanitizer: 400 interrupts')) throw Error('Native tests did not complete');
  console.log(output.toString()); process.exit(0);
}
const builds = [];
for (let pass = 0; pass < 2; pass++) {
  const output = compileInContainer(image, files, ['sh', '/src/native/gmp/build.sh', 'wasm'],
    "base64 -w0 /work/candidate.wasm; printf '\\n'; cat /work/siqs.txt", 600000, 'candidate').toString();
  const [base64, ...objects] = output.trim().split('\n');
  builds.push({ bytes: Buffer.from(base64, 'base64'), objects });
  console.log('Completed clean GMP/ECM build ' + (pass + 1));
}
if (!builds[0].bytes.equals(builds[1].bytes) || JSON.stringify(builds[0].objects) !== JSON.stringify(builds[1].objects)) {
  throw Error('Clean candidate builds differ');
}
const bytes = builds[0].bytes, module = new WebAssembly.Module(bytes);
const receipt = { image, emscripten: '4.0.15', upstreams,
  sourceHashes: Object.fromEntries(inputs.map(p => [p, sha(readFileSync(join(root, p)))])),
  cleanBuilds: 2, sha256: sha(bytes), bytes: bytes.length,
  imports: WebAssembly.Module.imports(module), exports: WebAssembly.Module.exports(module),
  memoryLimitBytes: 67108864, stackBytes: 1048576, siqsObjects: builds[0].objects,
  ecm: { parametrization: 'Suyama', B1: 2000, B2: 200000, curves: 32, stage2MemoryBytes: 16777216 },
  container: { network: 'none', cpus: 2, memory: '2g', workTmpfs: '512m', pids: 128, capabilities: 'none' } };
const generated = '// Generated by scripts/build-gmp.mjs; private evaluation artifact.\nexport const GMP_BASE64 = ' + JSON.stringify(bytes.toString('base64')) + ';\n';
const destination = join(root, 'src/engine/gmp-bytes.js'), record = join(root, 'native/gmp/build.json');
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== generated || JSON.stringify(JSON.parse(readFileSync(record))) !== JSON.stringify(receipt)) throw Error('Candidate build is stale');
} else {
  writeFileSync(destination, generated); writeFileSync(record, JSON.stringify(receipt, null, 2) + '\n');
}
console.log('Verified candidate WASM ' + bytes.length + ' bytes SHA256 ' + sha(bytes) + '; SIQS object-only 8/8');
