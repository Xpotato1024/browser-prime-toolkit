import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { Script } from 'node:vm';

const root = resolve(import.meta.dirname, '..');
// Explicit ordered source list, not a general JavaScript bundler.
const candidate = process.argv.includes('--candidate');
const siqs = process.argv.includes('--siqs');
const audit = process.argv.includes('--ecm-audit');
const native = process.argv.includes('--native-only');
if ([candidate, siqs, audit, native].filter(Boolean).length > 1) throw Error('Choose one Worker variant');
const paths = ['src/engine/options.js', 'src/engine/arithmetic.js', 'src/engine/result.js', 'src/engine/factor.js',
  ...(native ? [] : siqs ? ['src/engine/siqs-bytes.js', 'src/engine/siqs.js'] : candidate || audit ? ['src/engine/gmp-bytes.js', 'src/engine/gmp.js'] : ['src/engine/tinyqs-bytes.js', 'src/engine/tinyqs.js']),
  'src/worker/install.js', native ? 'src/worker/native-worker.js' : siqs ? 'src/worker/siqs-worker.js' : audit ? 'src/worker/ecm-audit-worker.js' : candidate ? 'src/worker/candidate-worker.js' : 'src/worker/factor-worker.js'];
const chunks = paths.map(path => {
  let source = readFileSync(resolve(root, path), 'utf8');
  source = source.replace(/^import \{[A-Za-z0-9_, ]+\} from '\.\.?\/[A-Za-z0-9_./-]+\.js';\n/gm, '');
  source = source.replace(/^export (?=(?:async )?(const|class|function) )/gm, '');
  if (/\b(import|export)\b/.test(source)) throw new Error('Unsupported module syntax: ' + path);
  return '// ' + path + '\n' + source;
});
const code = "'use strict';\n" + chunks.join('\n');
new Script(code); // Syntax only; never execute the source here.
const output = '// Generated by scripts/build-worker.mjs; do not edit.\nexport const WORKER_SOURCE = ' +
  JSON.stringify(code) + ';\n';
const destination = resolve(root, native ? 'src/worker/native-worker-source.js' : siqs ? 'src/worker/siqs-worker-source.js' : audit ? 'src/worker/ecm-audit-worker-source.js' : candidate ? 'src/worker/candidate-worker-source.js' : 'src/worker/worker-source.js');
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) throw new Error('Worker source is stale; run npm run build:worker');
} else writeFileSync(destination, output);
console.log('Verified bundled Worker: ' + Buffer.byteLength(code) + ' bytes, no runtime imports');
